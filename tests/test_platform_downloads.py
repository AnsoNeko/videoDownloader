"""Exercise real yt-dlp HTTP download/progress/output against isolated media.

Only platform metadata is stubbed; the MP4 is generated by FFmpeg and served
by a local HTTP server. No account cookies or live platform requests are used.
"""
import contextlib
import http.server
import json
import subprocess
import tempfile
import threading
import unittest
from pathlib import Path
from unittest.mock import patch

import app
from chinese_extractors import DOUYIN_USER_AGENT, FetcherDouyinIE, FetcherXhsIE, signed_douyin_params
from third_party.douyin_abogus import ABogus
from yt_dlp.extractor.bilibili import BiliBiliIE


class PlatformDownloadTests(unittest.TestCase):
    def test_signed_params_match_transmitted_query(self):
        captured = []

        def sign(instance, params):
            captured.append(dict(params))
            return "signature-fixture"

        with patch.object(ABogus, "get_value", sign):
            params = signed_douyin_params("12345")
        signature = params.pop("a_bogus")
        self.assertEqual(params, captured[0])
        self.assertEqual(params["msToken"], "")
        self.assertEqual(signature, "signature-fixture")
        self.assertIn(params["browser_version"], DOUYIN_USER_AGENT)
        # The actual stdlib SM3 signer also runs without optional crypto packages.
        self.assertTrue(signed_douyin_params("12345")["a_bogus"])

    def test_three_platforms_download_playable_mp4_and_report_completion(self):
        ffmpeg = app.detect_ffmpeg()
        if not ffmpeg:
            self.skipTest("FFmpeg is needed to generate a playable MP4 fixture")
        with tempfile.TemporaryDirectory() as temporary:
            root = Path(temporary)
            media = root / "fixture.mp4"
            subprocess.run([str(ffmpeg), "-hide_banner", "-loglevel", "error", "-y",
                            "-f", "lavfi", "-i", "color=c=blue:s=16x16:r=1",
                            "-f", "lavfi", "-i", "anullsrc=r=8000:cl=mono", "-t", "1",
                            "-c:v", "libx264", "-c:a", "aac", "-shortest", str(media)],
                           check=True, timeout=15, capture_output=True,
                           creationflags=subprocess.CREATE_NO_WINDOW if app.os.name == "nt" else 0)

            class Handler(http.server.BaseHTTPRequestHandler):
                def do_GET(self):
                    content = media.read_bytes()
                    self.send_response(200)
                    self.send_header("Content-Type", "video/mp4")
                    self.send_header("Content-Length", str(len(content)))
                    self.end_headers()
                    self.wfile.write(content)

                def log_message(self, *args):
                    pass

            server = http.server.ThreadingHTTPServer(("127.0.0.1", 0), Handler)
            thread = threading.Thread(target=server.serve_forever, daemon=True)
            thread.start()
            self.addCleanup(server.server_close)
            self.addCleanup(server.shutdown)
            media_url = f"http://127.0.0.1:{server.server_port}/fixture.mp4"
            detail = {"aweme_id": "123456", "desc": "抖音下载测试", "author": {"uid": "1", "nickname": "fixture"},
                      "video": {"duration": 1000, "width": 16, "height": 16, "play_addr": {"url_list": [media_url]}}}
            note_id = "674051740000000007027a15"
            page = "<script>window.__INITIAL_STATE__=" + json.dumps({"note": {"noteDetailMap": {note_id: {"note": {
                "title": "小红书下载测试", "video": {"media": {"stream": {"h264": [{"masterUrl": media_url,
                    "duration": 1000, "videoCodec": "h264", "audioCodec": "aac", "width": 16, "height": 16}]}}},
            }}}}}, ensure_ascii=False) + ";</script>"
            with contextlib.ExitStack() as stack:
                for key, value in (("RUNTIME_DIR", root), ("AUTH_DIR", root / "auth"),
                                   ("SETTINGS_PATH", root / "settings.json"), ("ERROR_LOG_PATH", root / "errors.log"),
                                   ("DOWNLOADS_DIR", root)):
                    stack.enter_context(patch.object(app, key, value))
                stack.enter_context(patch.object(app, "detect_cookie_file", return_value=None))
                # This goes through _signed_detail and the real Douyin format parser.
                stack.enter_context(patch.object(FetcherDouyinIE, "_download_json", return_value={"status_code": 0, "aweme_detail": detail}))
                stack.enter_context(patch.object(FetcherXhsIE, "_download_webpage", return_value=page))
                stack.enter_context(patch.object(BiliBiliIE, "_real_extract", return_value={
                    "id": "BV1EQQUBYEEB", "title": "B站下载测试", "formats": [{"format_id": "fixture",
                        "url": media_url, "ext": "mp4", "vcodec": "h264", "acodec": "aac"}]}))
                for platform, url in (("douyin", "https://www.douyin.com/video/123456"),
                                      ("xiaohongshu", f"https://www.xiaohongshu.com/explore/{note_id}?xsec_token=dummy"),
                                      ("bilibili", "https://www.bilibili.com/video/BV1EQQUBYEEB")):
                    with self.subTest(platform=platform):
                        directory = root / platform
                        directory.mkdir()
                        app.DOWNLOAD_JOBS[platform] = {"id": platform}
                        self.addCleanup(app.DOWNLOAD_JOBS.pop, platform, None)
                        app.run_download_job(platform, url, "", False, "", directory, use_saved_cookies=False)
                        job = app.get_job(platform)
                        self.assertEqual(job["status"], "completed", job.get("error"))
                        self.assertEqual(job["progress"], 100)
                        self.assertEqual((directory / job["file_name"]).read_bytes(), media.read_bytes())
                        self.assertGreater(job["downloaded_bytes"], 0)


if __name__ == "__main__":
    unittest.main()
